#!/usr/bin/env python3
"""Create real no-import Rust guest source for the Mantle component pipeline.

The explicit cohort's wasm-tools produces the WIT metadata. This command does
not build a component, create evidence, download tools, or rewrite a bundle.
"""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile


EFFECT_INTENT_SCHEMA = "lattice.operation-pack-wasm-effect-intents.v1"

GUEST = r'''#![no_std]

// Canonical ABI implementation for the exact import-free operation world.
// Every invocation gets a fresh bounded store; returned bytes are static and
// remain valid through post-return. No allocator or ambient WASI is linked.
#[used]
#[unsafe(link_section = "component-type:operation")]
static COMPONENT_TYPE: [u8; __METADATA_LENGTH__] = *include_bytes!("component-type.bin");

const PURE: &[u8] = b"{\"kind\":\"pure_result\",\"schema\":\"lattice.operation-pack-wasm-result.v1\",\"result\":{\"status\":\"pure\"}}";
const EFFECTS: &[u8] = include_bytes!("effect-output.json");
static mut HEAP: [u8; 65536] = [0; 65536];
static mut NEXT: usize = 0;
#[repr(align(4))]
struct ReturnArea([u32; 2]);
static mut RETURN: ReturnArea = ReturnArea([0; 2]);

#[unsafe(export_name = "wizer.initialize")]
pub extern "C" fn initialize() {
    unsafe { NEXT = 0; }
}

#[unsafe(export_name = "cabi_realloc")]
pub unsafe extern "C" fn realloc(old: u32, old_size: u32, align: u32, size: u32) -> u32 {
    if align == 0 || !align.is_power_of_two() || align > 65536 {
        core::arch::wasm32::unreachable();
    }
    if size == 0 { return align; }
    if old != 0 && size <= old_size { return old; }
    let next = unsafe { NEXT };
    let base = core::ptr::addr_of_mut!(HEAP).cast::<u8>() as usize;
    let start = match base.checked_add(next).and_then(|value| value.checked_add(align as usize - 1)) {
        Some(value) => (value & !(align as usize - 1)) - base,
        None => core::arch::wasm32::unreachable(),
    };
    let end = match start.checked_add(size as usize) {
        Some(value) if value <= 65536 => value,
        _ => core::arch::wasm32::unreachable(),
    };
    let pointer = unsafe { core::ptr::addr_of_mut!(HEAP).cast::<u8>().add(start) };
    if old != 0 {
        unsafe { core::ptr::copy_nonoverlapping(old as *const u8, pointer, old_size.min(size) as usize); }
    }
    unsafe { NEXT = end; }
    pointer as u32
}

#[unsafe(export_name = "lattice:operation-pack/methods@1.0.0#invoke")]
pub unsafe extern "C" fn invoke(method: u32, length: u32, _input: u32, _input_length: u32) -> u32 {
    let method = unsafe { core::slice::from_raw_parts(method as *const u8, length as usize) };
    let output = match method {
        b"pure" => PURE,
        b"effects" => EFFECTS,
        b"invalid_output" => b"{\"kind\":\"unrecognized\"}",
        b"trap" => core::arch::wasm32::unreachable(),
        b"spin" => loop { core::hint::spin_loop(); },
        _ => core::arch::wasm32::unreachable(),
    };
    let area = core::ptr::addr_of_mut!(RETURN);
    unsafe { (*area).0 = [output.as_ptr() as u32, output.len() as u32]; }
    area as u32
}

#[unsafe(export_name = "cabi_post_lattice:operation-pack/methods@1.0.0#invoke")]
pub extern "C" fn post_return(_result: u32) {
    // Static outputs need no deallocation. Host cleanup remains mandatory.
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo<'_>) -> ! {
    core::arch::wasm32::unreachable()
}
'''

CARGO = '''[package]
name = "lattice-operation-pack-guest"
version = "0.1.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib"]

[profile.release]
panic = "abort"
opt-level = "s"
lto = true
codegen-units = 1
'''

LOCK = '''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "lattice-operation-pack-guest"
version = "0.1.0"
'''


def effect_bytes(path: Path) -> bytes:
    value = json.loads(path.read_bytes())
    if set(value) != {"kind", "schema", "intents", "result"}:
        raise ValueError("effect output must use the closed result envelope")
    if value["kind"] != "effect_intents" or value["schema"] != EFFECT_INTENT_SCHEMA:
        raise ValueError("effect output has an unsupported result contract")
    if not isinstance(value["intents"], list) or not value["intents"]:
        raise ValueError("effect output must contain actual operation intents")
    for intent in value["intents"]:
        if not isinstance(intent, dict) or set(intent) != {"type_id", "type_revision", "instance_id", "method", "arguments"}:
            raise ValueError("effect intent has unknown or missing fields")
        if any(not isinstance(intent[key], str) or not intent[key] for key in ("type_id", "type_revision", "instance_id", "method")):
            raise ValueError("effect intent identity fields must be nonempty strings")
        if not isinstance(intent["arguments"], dict):
            raise ValueError("effect intent arguments must be structured")
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wasm-tools", type=Path, required=True, help="Exact acquired cohort executable; no PATH lookup")
    parser.add_argument("--effect-output", type=Path, required=True, help="Closed JSON effect result bound to real operation revisions")
    parser.add_argument("--destination", type=Path, required=True, help="Create-only source directory")
    parser.add_argument("--wit", type=Path, default=Path(__file__).resolve().parents[1] / "contracts/operation-pack-wasm.wit")
    args = parser.parse_args()
    if not args.wasm_tools.is_absolute():
        parser.error("--wasm-tools must be an explicit absolute executable path")
    output = effect_bytes(args.effect_output)
    wit = args.wit.read_bytes()
    with tempfile.TemporaryDirectory(prefix="lattice-component-metadata-") as temporary:
        root = Path(temporary)
        selected = root / "operation.wit"
        selected.write_bytes(wit)
        metadata = root / "component-type.bin"
        subprocess.run(
            [str(args.wasm_tools), "component", "embed", str(selected), "--world", "operation", "--only-custom", "--output", str(metadata)],
            env={}, check=True,
        )
        encoded = metadata.read_bytes()
        if not encoded.startswith(b"\0asm\x0d\0\x01\0"):
            raise ValueError("wasm-tools did not produce genuine component metadata")
        args.destination.mkdir()
        (args.destination / "src").mkdir()
        (args.destination / "wit").mkdir()
        (args.destination / "Cargo.toml").write_text(CARGO, encoding="ascii")
        (args.destination / "Cargo.lock").write_text(LOCK, encoding="ascii")
        (args.destination / "wit/operation.wit").write_bytes(wit)
        (args.destination / "src/component-type.bin").write_bytes(encoded)
        (args.destination / "src/effect-output.json").write_bytes(output)
        (args.destination / "src/lib.rs").write_text(GUEST.replace("__METADATA_LENGTH__", str(len(encoded))), encoding="ascii")
    print(args.destination)


if __name__ == "__main__":
    main()
