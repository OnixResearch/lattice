/// Provider-neutral model input modality.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum InputModality {
    /// Text input.
    Text,
    /// Image input.
    Image,
    /// Video input.
    Video,
}

impl InputModality {
    /// Returns the stable modality label.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Text => "text",
            Self::Image => super::IMAGE_MODALITY,
            Self::Video => "video",
        }
    }
}

/// Supported image media type.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ImageMediaType {
    /// `image/png`.
    Png,
    /// `image/jpeg`.
    Jpeg,
    /// `image/webp`.
    Webp,
    /// `image/gif`.
    Gif,
}

impl ImageMediaType {
    /// Parses a supported image media type.
    ///
    /// # Errors
    ///
    /// Returns [`super::Error`] when the media type is empty, unsafe, or unsupported.
    pub fn parse(raw: &str) -> Result<Self, super::Error> {
        let normalized = super::check::normalized_safe_text(super::MEDIA_TYPE_FIELD, raw)?;
        match normalized.as_str() {
            "image/png" => Ok(Self::Png),
            "image/jpeg" => Ok(Self::Jpeg),
            "image/webp" => Ok(Self::Webp),
            "image/gif" => Ok(Self::Gif),
            _unsupported => Err(super::Error::UnsupportedMediaType { value: normalized }),
        }
    }

    /// Returns the stable media type string.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Png => "image/png",
            Self::Jpeg => "image/jpeg",
            Self::Webp => "image/webp",
            Self::Gif => "image/gif",
        }
    }
}

/// Trust metadata attached to an image source descriptor.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ImageSourceTrust {
    /// User explicitly provided or selected the image.
    UserProvided,
    /// Image comes from a workspace artifact admitted by the host.
    WorkspaceArtifact,
    /// Image was generated by a trusted host-side transform.
    HostGenerated,
    /// Image comes from an external source and is not trusted.
    ExternalUntrusted,
}

impl ImageSourceTrust {
    /// Returns the stable source-trust label.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::UserProvided => "user_provided",
            Self::WorkspaceArtifact => "workspace_artifact",
            Self::HostGenerated => "host_generated",
            Self::ExternalUntrusted => "external_untrusted",
        }
    }
}

/// Host-declared image rendering/detail preference.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ImageDetailPreference {
    /// Let the provider adapter choose its default.
    Auto,
    /// Prefer low detail or thumbnail-style processing.
    Low,
    /// Prefer high detail processing.
    High,
}

impl ImageDetailPreference {
    /// Returns the stable detail label.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Low => "low",
            Self::High => "high",
        }
    }
}
