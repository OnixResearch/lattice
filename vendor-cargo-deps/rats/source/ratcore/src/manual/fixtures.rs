/// Builds the checked-in shared snapshot baseline artifacts.
#[must_use]
pub fn built_in_snapshot_artifacts() -> Vec<SnapshotArtifact> {
    debug_assert_eq!(BUILT_IN_SNAPSHOT_SPECS.len(), BASELINE_SNAPSHOT_COUNT);
    BUILT_IN_SNAPSHOT_SPECS
        .iter()
        .copied()
        .map(BuiltInSnapshotSpec::artifact)
        .collect()
}

/// Builds the checked-in shared snapshot baseline manifest entries.
#[must_use]
pub fn built_in_snapshot_manifest_entries() -> Vec<SnapshotManifestEntry> {
    debug_assert_eq!(BUILT_IN_SNAPSHOT_SPECS.len(), BASELINE_SNAPSHOT_COUNT);
    BUILT_IN_SNAPSHOT_SPECS
        .iter()
        .copied()
        .map(BuiltInSnapshotSpec::manifest_entry)
        .collect()
}

/// Builds the fixture IDs included in the shared snapshot baseline.
#[must_use]
pub fn built_in_snapshot_fixture_ids() -> std::collections::BTreeSet<String> {
    built_in_component_doc_sources()
        .into_iter()
        .map(|source| source.component_id)
        .collect()
}

