#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct BuiltInSnapshotSpec {
    fixture_id: &'static str,
    renderer: &'static str,
    artifact_path: &'static str,
    artifact_text: &'static str,
    size: SnapshotSize,
}

impl BuiltInSnapshotSpec {
    const fn new(
        fixture_id: &'static str,
        renderer: &'static str,
        artifact_path: &'static str,
        artifact_text: &'static str,
        size: SnapshotSize,
    ) -> Self {
        Self {
            fixture_id,
            renderer,
            artifact_path,
            artifact_text,
            size,
        }
    }

    fn artifact(self) -> SnapshotArtifact {
        SnapshotArtifact::new(self.artifact_path, self.artifact_text.as_bytes().to_vec())
    }

    fn manifest_entry(self) -> SnapshotManifestEntry {
        SnapshotManifestEntry::new(
            self.fixture_id,
            self.renderer,
            self.artifact_path,
            self.artifact_text.as_bytes(),
            self.size,
        )
    }
}

