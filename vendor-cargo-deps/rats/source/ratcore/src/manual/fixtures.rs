/// Builds generated component documents for the shared snapshot baseline.
#[must_use]
pub fn built_in_generated_component_documents() -> Vec<GeneratedComponentDocument> {
    let entries = built_in_snapshot_manifest_entries();
    build_generated_component_documents(
        &built_in_component_doc_sources(),
        &built_in_component_pages(),
        &entries,
    )
}

/// Builds parity rows covered by the shared snapshot baseline.
#[must_use]
pub fn built_in_snapshot_parity_rows() -> Vec<crate::showcase_fixtures::FixtureParityRow> {
    let fixture_ids = built_in_snapshot_fixture_ids();
    crate::showcase_fixtures::built_in_fixture_parity_rows()
        .into_iter()
        .filter(|row| fixture_ids.contains(&row.fixture_id))
        .collect()
}

