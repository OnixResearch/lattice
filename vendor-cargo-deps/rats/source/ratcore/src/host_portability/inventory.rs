/// Builds one capability contract per distinct capability in the effect inventory.
#[must_use]
pub fn built_in_host_capability_contracts() -> Vec<super::HostCapabilityContract> {
    let mut seen = std::collections::BTreeSet::new();
    let mut contracts = Vec::new();
    for effect in built_in_host_effects() {
        if !seen.insert(effect.capability.clone()) {
            continue;
        }
        let authority = if effect.disposition == super::PortabilityDisposition::MigrationBlocker {
            super::CapabilityAuthority::Caller
        } else {
            super::CapabilityAuthority::Rats
        };
        contracts.push(super::HostCapabilityContract {
            id: effect.capability,
            owner: effect.owner,
            role: effect.role,
            target_scope: effect.target_scope,
            diagnostics: effect.diagnostics,
            fallback: effect.fallback,
            state_kind: super::CapabilityStateKind::PlainValues,
            authority,
            attachments: super::AuthorityAttachments::COMPLETE,
            disposition: effect.disposition,
        });
    }
    contracts.sort_by(|left, right| left.id.cmp(&right.id));
    contracts
}
