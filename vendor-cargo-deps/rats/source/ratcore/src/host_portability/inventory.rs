#[derive(Clone, Copy)]
struct EffectSeed {
    id: &'static str,
    package: &'static str,
    path: &'static str,
    surface: super::SourceSurface,
    kind: super::HostEffectKind,
    direction: super::EffectDirection,
    owner: &'static str,
    role: super::PortabilityRole,
    scope: &'static str,
    defaults: super::DefaultFeatureDisposition,
    capability: &'static str,
    diagnostics: &'static str,
    fallback: &'static str,
    disposition: super::PortabilityDisposition,
    change: Option<&'static str>,
    scan: super::EffectScanClass,
    count: usize,
}

/// Returns the deterministic ambient-effect and runtime-dependency inventory.
#[must_use]
pub fn built_in_host_effects() -> Vec<super::HostEffectCoordinate> {
    let mut rows = EFFECT_SEEDS
        .iter()
        .map(|seed| super::HostEffectCoordinate {
            id: super::HostEffectId::new(seed.id),
            package: seed.package.to_string(),
            path: seed.path.to_string(),
            surface: seed.surface,
            kind: seed.kind,
            direction: seed.direction,
            owner: seed.owner.to_string(),
            role: seed.role,
            target_scope: super::HostTargetScopeId::new(seed.scope),
            defaults: seed.defaults,
            capability: super::HostCapabilityId::new(seed.capability),
            diagnostics: seed.diagnostics.to_string(),
            fallback: seed.fallback.to_string(),
            disposition: seed.disposition,
            dependent_change: seed.change.map(str::to_string),
            scan_class: seed.scan,
            scan_match_count: seed.count,
        })
        .collect::<Vec<_>>();
    rows.sort_by(|left, right| left.id.cmp(&right.id));
    rows
}

