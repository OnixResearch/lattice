#[derive(Clone, Copy)]
struct PackageSeed {
    id: &'static str,
    package: &'static str,
    path: &'static str,
    owner: &'static str,
    role: super::PortabilityRole,
    surface: super::SourceSurface,
    scope: &'static str,
    defaults: super::DefaultFeatureDisposition,
    default_features: &'static str,
    disposition: super::PortabilityDisposition,
    change: Option<&'static str>,
}

/// Returns the deterministic package/source-slice inventory.
#[must_use]
pub fn built_in_package_surfaces() -> Vec<super::PackageSurface> {
    let mut rows = PACKAGE_SEEDS
        .iter()
        .map(|seed| super::PackageSurface {
            id: super::PortabilitySurfaceId::new(seed.id),
            package: seed.package.to_string(),
            path: seed.path.to_string(),
            owner: seed.owner.to_string(),
            role: seed.role,
            surface: seed.surface,
            target_scope: super::HostTargetScopeId::new(seed.scope),
            defaults: seed.defaults,
            default_features: seed.default_features.to_string(),
            disposition: seed.disposition,
            dependent_change: seed.change.map(str::to_string),
        })
        .collect::<Vec<_>>();
    rows.sort_by(|left, right| left.id.cmp(&right.id));
    rows
}

