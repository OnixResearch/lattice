//! Deterministic generated inventory renderers.

use std::fmt::Write as _;

/// Renders the canonical package/source-slice inventory as TSV.
#[must_use]
pub fn render_package_inventory_tsv(rows: &[super::PackageSurface]) -> String {
    let mut ordered = rows.to_vec();
    ordered.sort_by(|left, right| left.id.cmp(&right.id));
    let mut output = String::from(
        "id\tpackage\tpath\towner\trole\tsurface\ttarget_scope\tdefaults\tdefault_features\tdisposition\tdependent_change\n",
    );
    for row in ordered {
        writeln!(
            output,
            "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}",
            row.id,
            row.package,
            row.path,
            row.owner,
            row.role.as_str(),
            row.surface.as_str(),
            row.target_scope,
            row.defaults.as_str(),
            row.default_features,
            row.disposition.as_str(),
            row.dependent_change.as_deref().unwrap_or("-"),
        )
        .expect("writing to String cannot fail");
    }
    output
}

