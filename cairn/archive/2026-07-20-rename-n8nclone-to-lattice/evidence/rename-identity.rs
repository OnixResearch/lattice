#!/usr/bin/env -S nix develop . -c cargo -q -Zscript

use std::env;
use std::fs;
use std::path::Path;
use std::path::PathBuf;
use std::process::ExitCode;

const EXECUTE_ARG: &str = "--execute";
const SELF_TEST_ARG: &str = "--self-test";
const EXPECTED_ARG_COUNT: usize = 2;
const SUCCESS_EXIT_CODE: u8 = 0;
const FAILURE_EXIT_CODE: u8 = 1;
const TEXT_EXTENSIONS: &[&str] = &["rs", "md", "ncl"];
const GLOBAL_PATHS: &[&str] = &["README.md", "examples"];
const RUST_PATHS: &[&str] = &["src", "tests"];
const ACCEPTED_SPEC_PATH: &str = "cairn/specs";
const GLOBAL_REPLACEMENTS: &[(&str, &str)] = &[
    ("N8NCLONE", "LATTICE"),
    ("N8nclone", "Lattice"),
    ("n8nclone", "lattice"),
];
const RUST_REPLACEMENTS: &[(&str, &str)] = &[
    ("n8nclone::", "lattice::"),
    ("CARGO_BIN_EXE_n8nclone", "CARGO_BIN_EXE_lattice"),
    ("n8nclone.redb", "lattice.redb"),
    (".n8nclone", ".lattice"),
    ("N8NCLONE_", "LATTICE_"),
    ("/tmp/n8nclone.log", "/tmp/lattice.log"),
    ("/n8nclone/", "/lattice/"),
    ("n8nclone/0.1.0", "lattice/0.1.0"),
    ("Generated by n8nclone", "Generated by Lattice"),
    ("starting n8nclone", "starting lattice"),
];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mode {
    DryRun,
    Execute,
    SelfTest,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Rewrite {
    text: String,
    replacements: usize,
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::from(SUCCESS_EXIT_CODE),
        Err(error) => {
            eprintln!("{error}");
            ExitCode::from(FAILURE_EXIT_CODE)
        }
    }
}

fn run() -> Result<(), String> {
    let args: Vec<String> = env::args().collect();
    let mode = parse_mode(&args)?;
    if mode == Mode::SelfTest {
        self_test()?;
        println!("identity rewrite self-test passed");
        return Ok(());
    }

    let root = env::current_dir().map_err(|error| format!("failed to read current directory: {error}"))?;
    let mut changed_files = 0usize;
    let mut replacement_count = 0usize;

    for relative in GLOBAL_PATHS {
        let path = root.join(relative);
        rewrite_path(&path, GLOBAL_REPLACEMENTS, mode, &mut changed_files, &mut replacement_count)?;
    }
    for relative in RUST_PATHS {
        let path = root.join(relative);
        rewrite_path(&path, RUST_REPLACEMENTS, mode, &mut changed_files, &mut replacement_count)?;
    }
    rewrite_spec_path(&root.join(ACCEPTED_SPEC_PATH), mode, &mut changed_files, &mut replacement_count)?;

    println!("mode={mode:?} changed_files={changed_files} replacements={replacement_count}");
    Ok(())
}

fn parse_mode(args: &[String]) -> Result<Mode, String> {
    if args.len() == 1 {
        return Ok(Mode::DryRun);
    }
    if args.len() != EXPECTED_ARG_COUNT {
        return Err(format!("usage: {} [{EXECUTE_ARG}|{SELF_TEST_ARG}]", args[0]));
    }
    match args[1].as_str() {
        EXECUTE_ARG => Ok(Mode::Execute),
        SELF_TEST_ARG => Ok(Mode::SelfTest),
        argument => Err(format!("unsupported argument: {argument}")),
    }
}

fn rewrite_path(
    path: &Path,
    replacements: &[(&str, &str)],
    mode: Mode,
    changed_files: &mut usize,
    replacement_count: &mut usize,
) -> Result<(), String> {
    if path.is_dir() {
        let mut entries: Vec<PathBuf> = fs::read_dir(path)
            .map_err(|error| format!("failed to read {}: {error}", path.display()))?
            .map(|entry| {
                entry
                    .map(|value| value.path())
                    .map_err(|error| format!("failed to inspect {}: {error}", path.display()))
            })
            .collect::<Result<_, _>>()?;
        entries.sort();
        for entry in entries {
            rewrite_path(&entry, replacements, mode, changed_files, replacement_count)?;
        }
        return Ok(());
    }

    if path.ends_with("src/config/mod.rs") || path.ends_with("src/config/identity.rs") || !is_text_path(path) {
        return Ok(());
    }
    let original = fs::read_to_string(path).map_err(|error| format!("failed to read {}: {error}", path.display()))?;
    let rewrite = rewrite_text(&original, replacements);
    if rewrite.replacements == 0 {
        return Ok(());
    }

    *changed_files = changed_files.saturating_add(1);
    *replacement_count = replacement_count.saturating_add(rewrite.replacements);
    println!("{}: {}", path.display(), rewrite.replacements);
    if mode == Mode::Execute {
        fs::write(path, rewrite.text).map_err(|error| format!("failed to write {}: {error}", path.display()))?;
    }
    Ok(())
}

fn rewrite_text(input: &str, replacements: &[(&str, &str)]) -> Rewrite {
    let mut text = input.to_string();
    let mut replacement_count = 0usize;
    for (old, new) in replacements {
        replacement_count = replacement_count.saturating_add(text.matches(old).count());
        text = text.replace(old, new);
    }
    Rewrite {
        text,
        replacements: replacement_count,
    }
}

fn rewrite_spec_text(input: &str) -> Rewrite {
    let mut text = String::with_capacity(input.len());
    let mut replacement_count = 0usize;
    for line in input.split_inclusive('\n') {
        let split = line
            .find("r[")
            .and_then(|marker_start| line[marker_start..].find(']').map(|offset| marker_start + offset + 1));
        let (stable_prefix, prose) = split.map_or(("", line), |index| line.split_at(index));
        let prose_rewrite = rewrite_text(prose, &[("`n8nclone`", "`lattice`"), ("n8nclone", "Lattice")]);
        text.push_str(stable_prefix);
        text.push_str(&prose_rewrite.text);
        replacement_count = replacement_count.saturating_add(prose_rewrite.replacements);
    }
    Rewrite {
        text,
        replacements: replacement_count,
    }
}

fn rewrite_spec_path(
    path: &Path,
    mode: Mode,
    changed_files: &mut usize,
    replacement_count: &mut usize,
) -> Result<(), String> {
    if path.is_dir() {
        let mut entries: Vec<PathBuf> = fs::read_dir(path)
            .map_err(|error| format!("failed to read {}: {error}", path.display()))?
            .map(|entry| {
                entry
                    .map(|value| value.path())
                    .map_err(|error| format!("failed to inspect {}: {error}", path.display()))
            })
            .collect::<Result<_, _>>()?;
        entries.sort();
        for entry in entries {
            rewrite_spec_path(&entry, mode, changed_files, replacement_count)?;
        }
        return Ok(());
    }
    if path.file_name().and_then(|name| name.to_str()) != Some("spec.md") {
        return Ok(());
    }

    let original = fs::read_to_string(path).map_err(|error| format!("failed to read {}: {error}", path.display()))?;
    let rewrite = rewrite_spec_text(&original);
    if rewrite.replacements == 0 {
        return Ok(());
    }
    *changed_files = changed_files.saturating_add(1);
    *replacement_count = replacement_count.saturating_add(rewrite.replacements);
    println!("{}: {}", path.display(), rewrite.replacements);
    if mode == Mode::Execute {
        fs::write(path, rewrite.text).map_err(|error| format!("failed to write {}: {error}", path.display()))?;
    }
    Ok(())
}

fn is_text_path(path: &Path) -> bool {
    if path.file_name().and_then(|name| name.to_str()) == Some("README.md") {
        return true;
    }
    path.extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| TEXT_EXTENSIONS.contains(&extension))
}

fn self_test() -> Result<(), String> {
    let positive =
        rewrite_text("use n8nclone::engine; CARGO_BIN_EXE_n8nclone .n8nclone N8NCLONE_DATA_DIR", RUST_REPLACEMENTS);
    if positive.text != "use lattice::engine; CARGO_BIN_EXE_lattice .lattice LATTICE_DATA_DIR" {
        return Err(format!("positive rewrite mismatch: {}", positive.text));
    }
    if positive.replacements != 4 {
        return Err(format!("positive replacement count mismatch: {}", positive.replacements));
    }

    let stable = "r[n8nclone.workflow_execution.runner_core] n8nclone-webhook-signature:v1";
    let negative = rewrite_text(stable, RUST_REPLACEMENTS);
    if negative.text != stable || negative.replacements != 0 {
        return Err("stable protocol or evidence identity was rewritten".to_string());
    }

    let spec = rewrite_spec_text(
        "r[n8nclone.workflow_execution.runner_core] The n8nclone shell MUST run.\n- WHEN n8nclone starts\n",
    );
    let expected_spec =
        "r[n8nclone.workflow_execution.runner_core] The Lattice shell MUST run.\n- WHEN Lattice starts\n";
    if spec.text != expected_spec {
        return Err(format!("spec rewrite mismatch: {}", spec.text));
    }
    Ok(())
}
