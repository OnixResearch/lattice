//! Typed Nickel authoring and deterministic rendering for orchestration data.

use std::fmt;
use std::path::Path;

use serde::Serialize;

use super::core::OrchestrationDefinition;
use super::core::RevisionProposal;
use crate::config;

const INDENT_STEP: usize = 2;
const DEFINITION_HEADER: &str = "# Generated by Lattice — edit and re-import\n";
const DEFINITION_CONTRACT: &str = "let WorkflowRevision = { workflow_name | String, content_hash | String } in\nlet RetryPolicy = { max_observed_failure_retries | Number } in\nlet BudgetDimensions = { rounds | Bool, agent_invocations | Bool, tokens | Bool, monetary_microunits | Bool, duration_millis | Bool } in\nlet BudgetVector = { rounds | Number, agent_invocations | Number, tokens | Number, monetary_microunits | Number, duration_millis | Number } in\nlet BudgetPolicy = { enforced | BudgetDimensions, limits | BudgetVector, per_round_upper_bound | BudgetVector } in\nlet AuthorityPolicy = { approvers | Array String } in\nlet TriggerBinding = { trigger_id | String, kind | String } in\nlet RedactionPolicy = { retain_safe_summaries | Bool } in\nlet OrchestrationDefinition = { schema_version | Number, id | String, objective | String, workflow | WorkflowRevision, completion | String, retry | optional | RetryPolicy, budgets | BudgetPolicy, authority | AuthorityPolicy, triggers | Array TriggerBinding, redaction | RedactionPolicy } in\n";
const PROPOSAL_HEADER: &str = "# Generated Lattice orchestration proposal\n";
const PROPOSAL_CONTRACT: &str = "let WorkflowRevision = { workflow_name | String, content_hash | String } in\nlet RevisionProposal = { id | String, instance_id | String, base_definition_revision | String, base_epoch | Number, base_workflow_revision | WorkflowRevision, successor | WorkflowRevision, safe_summary | String } in\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OrchestrationFormatError {
    Nickel(String),
    Json(String),
    Render(String),
}

impl fmt::Display for OrchestrationFormatError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Nickel(message) => write!(formatter, "Nickel orchestration error: {message}"),
            Self::Json(message) => write!(formatter, "orchestration format error: {message}"),
            Self::Render(message) => write!(formatter, "orchestration render error: {message}"),
        }
    }
}

impl std::error::Error for OrchestrationFormatError {}

// r[impl lattice.agent_orchestration.format]
pub fn load_definition_nickel_file(path: &Path) -> Result<OrchestrationDefinition, OrchestrationFormatError> {
    let json = config::load_nickel_as_json(path)
        .map_err(|_| OrchestrationFormatError::Nickel("definition evaluation failed".to_string()))?;
    serde_json::from_value(json).map_err(|error| OrchestrationFormatError::Json(error.to_string()))
}

// r[impl lattice.agent_orchestration.format]
// r[impl lattice.agent_orchestration.observed_failure_retry]
pub fn definition_to_nickel(definition: &OrchestrationDefinition) -> Result<String, OrchestrationFormatError> {
    render_with_contract(DEFINITION_HEADER, DEFINITION_CONTRACT, "OrchestrationDefinition", definition)
}

pub fn load_proposal_nickel_file(path: &Path) -> Result<RevisionProposal, OrchestrationFormatError> {
    let json = config::load_nickel_as_json(path)
        .map_err(|_| OrchestrationFormatError::Nickel("proposal evaluation failed".to_string()))?;
    serde_json::from_value(json).map_err(|error| OrchestrationFormatError::Json(error.to_string()))
}

pub fn proposal_to_nickel(proposal: &RevisionProposal) -> Result<String, OrchestrationFormatError> {
    render_with_contract(PROPOSAL_HEADER, PROPOSAL_CONTRACT, "RevisionProposal", proposal)
}

// r[impl lattice.agent_orchestration.format]
pub fn reject_default_n8n_orchestration_export() -> Result<(), OrchestrationFormatError> {
    Err(OrchestrationFormatError::Render(
        "n8n export has no exact mapping for Lattice objectives, approvals, budgets, revisions, or multi-round state"
            .to_string(),
    ))
}

fn render_with_contract<T: Serialize>(
    header: &str,
    contract: &str,
    contract_name: &str,
    value: &T,
) -> Result<String, OrchestrationFormatError> {
    let json = serde_json::to_value(value).map_err(|error| OrchestrationFormatError::Render(error.to_string()))?;
    let body = render_nickel_value(&json, 0)?;
    Ok(format!("{header}{contract}({body}) | {contract_name}\n"))
}

fn render_nickel_value(value: &serde_json::Value, indent: usize) -> Result<String, OrchestrationFormatError> {
    match value {
        serde_json::Value::Null => Ok("null".to_string()),
        serde_json::Value::Bool(value) => Ok(value.to_string()),
        serde_json::Value::Number(value) => Ok(value.to_string()),
        serde_json::Value::String(value) => {
            serde_json::to_string(value).map_err(|error| OrchestrationFormatError::Render(error.to_string()))
        }
        serde_json::Value::Array(values) => render_array(values, indent),
        serde_json::Value::Object(fields) => render_object(fields, indent),
    }
}

fn render_array(values: &[serde_json::Value], indent: usize) -> Result<String, OrchestrationFormatError> {
    if values.is_empty() {
        return Ok("[]".to_string());
    }
    let child_indent = indent.saturating_add(INDENT_STEP);
    let padding = " ".repeat(child_indent);
    let mut output = String::from("[\n");
    for value in values {
        output.push_str(&padding);
        output.push_str(&render_nickel_value(value, child_indent)?);
        output.push_str(",\n");
    }
    output.push_str(&" ".repeat(indent));
    output.push(']');
    Ok(output)
}

fn render_object(
    fields: &serde_json::Map<String, serde_json::Value>,
    indent: usize,
) -> Result<String, OrchestrationFormatError> {
    if fields.is_empty() {
        return Ok("{}".to_string());
    }
    let child_indent = indent.saturating_add(INDENT_STEP);
    let padding = " ".repeat(child_indent);
    let mut entries = fields.iter().collect::<Vec<_>>();
    entries.sort_by_key(|(name, _)| *name);
    let mut output = String::from("{\n");
    for (name, value) in entries {
        output.push_str(&padding);
        output.push_str(name);
        output.push_str(" = ");
        output.push_str(&render_nickel_value(value, child_indent)?);
        output.push_str(",\n");
    }
    output.push_str(&" ".repeat(indent));
    output.push('}');
    Ok(output)
}
