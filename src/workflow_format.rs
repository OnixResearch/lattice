pub fn load_workflow_nickel_file(path: &Path) -> Result<Workflow, WorkflowFormatError> {
    let json = config::load_nickel_as_json(path).map_err(WorkflowFormatError::Nickel)?;
    let portable = serde_json::from_value(json).map_err(|error| WorkflowFormatError::Json(error.to_string()))?;
    validate_portable_identity(&portable)?;
    let resolved_agent_prompts = load_markdown_agent_prompts(path, &portable)?;
    portable_to_runtime_with_agent_prompts(portable, &resolved_agent_prompts)
}

fn empty_prompt_files() -> Vec<String> {
    Vec::new()
}

fn load_markdown_agent_prompts(
    workflow_path: &Path,
    portable: &PortableWorkflow,
) -> Result<HashMap<u64, String>, WorkflowFormatError> {
    let workflow_root = workflow_path.parent().unwrap_or_else(|| Path::new("."));
    let mut prompts = HashMap::with_capacity(portable.configs.len());

    for config in &portable.configs {
        if config.kind != "agent" {
            continue;
        }
        let Some(prompt_file) = prompt_file_for_loading(config)? else {
            continue;
        };
        let canonical_root = workflow_root.canonicalize().map_err(|error| {
            agent_prompt_file_error(
                config.node_id,
                prompt_file,
                format!("workflow root could not be resolved: {error}"),
            )
        })?;
        let relative_path = validate_markdown_prompt_path(config.node_id, prompt_file)?;
        let prompt = read_markdown_agent_prompt(config.node_id, prompt_file, &canonical_root, &relative_path)?;
        prompts.insert(config.node_id, prompt);
    }
    debug_assert!(prompts.len() <= portable.configs.len());
    debug_assert!(
        prompts
            .keys()
            .all(|node_id| portable.configs.iter().any(|config| config.node_id == *node_id && config.kind == "agent"))
    );
    Ok(prompts)
}

fn prompt_file_for_loading(config: &PortableNodeConfig) -> Result<Option<&str>, WorkflowFormatError> {
    if config.agent_prompt_file.len() > MAX_OPTIONAL_AGENT_VALUES {
        return Err(invalid_agent_prompt_source(
            config.node_id,
            format!("{} prompt files declared; expected zero or one", config.agent_prompt_file.len()),
        ));
    }
    let Some(prompt_file) = config.agent_prompt_file.first() else {
        return Ok(None);
    };
    if !config.agent_prompt.trim().is_empty() {
        return Err(invalid_agent_prompt_source(
            config.node_id,
            "inline prompt and prompt file are both declared".to_string(),
        ));
    }
    Ok(Some(prompt_file.as_str()))
}

fn validate_markdown_prompt_path(node_id: u64, prompt_file: &str) -> Result<PathBuf, WorkflowFormatError> {
    if prompt_file.trim().is_empty() {
        return Err(invalid_agent_prompt_source(node_id, "prompt file path is empty".to_string()));
    }
    let path = Path::new(prompt_file);
    if path.is_absolute() {
        return Err(invalid_agent_prompt_source(
            node_id,
            "prompt file path must be relative to the workflow root".to_string(),
        ));
    }
    if path.extension().and_then(|extension| extension.to_str()) != Some(MARKDOWN_EXTENSION) {
        return Err(invalid_agent_prompt_source(node_id, "prompt file must use the .md extension".to_string()));
    }
    if path.components().any(|component| !matches!(component, std::path::Component::Normal(_))) {
        return Err(invalid_agent_prompt_source(
            node_id,
            "prompt file path must not contain traversal or platform root components".to_string(),
        ));
    }
    debug_assert!(!path.is_absolute());
    debug_assert!(path.components().all(|component| matches!(component, std::path::Component::Normal(_))));
    Ok(path.to_path_buf())
}

fn read_markdown_agent_prompt(
    node_id: u64,
    prompt_file: &str,
    canonical_root: &Path,
    relative_path: &Path,
) -> Result<String, WorkflowFormatError> {
    let candidate = canonical_root.join(relative_path);
    let canonical_candidate = candidate.canonicalize().map_err(|error| {
        agent_prompt_file_error(node_id, prompt_file, format!("path could not be resolved: {error}"))
    })?;
    if !canonical_candidate.starts_with(canonical_root) {
        return Err(agent_prompt_file_error(
            node_id,
            prompt_file,
            "resolved path escapes the workflow root".to_string(),
        ));
    }
    debug_assert!(canonical_candidate.starts_with(canonical_root));

    let file = std::fs::File::open(&canonical_candidate)
        .map_err(|error| agent_prompt_file_error(node_id, prompt_file, format!("file could not be opened: {error}")))?;
    let mut bytes = Vec::new();
    file.take(MARKDOWN_AGENT_PROMPT_READ_LIMIT_U64)
        .read_to_end(&mut bytes)
        .map_err(|error| agent_prompt_file_error(node_id, prompt_file, format!("file could not be read: {error}")))?;
    if bytes.len() > MAX_MARKDOWN_AGENT_PROMPT_BYTES {
        return Err(agent_prompt_file_error(
            node_id,
            prompt_file,
            format!("file exceeds the {MAX_MARKDOWN_AGENT_PROMPT_BYTES}-byte limit"),
        ));
    }
    let prompt = String::from_utf8(bytes)
        .map_err(|error| agent_prompt_file_error(node_id, prompt_file, format!("file is not valid UTF-8: {error}")))?;
    if prompt.trim().is_empty() {
        return Err(agent_prompt_file_error(node_id, prompt_file, "file is empty".to_string()));
    }
    debug_assert!(prompt.len() <= MAX_MARKDOWN_AGENT_PROMPT_BYTES);
    Ok(prompt)
}

fn agent_prompt_file_error(node_id: u64, path: &str, message: String) -> WorkflowFormatError {
    WorkflowFormatError::AgentPromptFile {
        node_id,
        path: path.to_string(),
        message,
    }
}
