//! Portable workflow import/export formats.
//!
//! The pure core converts between `Workflow` and a portable data model. Nickel
//! evaluation and filesystem access stay in shell helpers.

use std::collections::HashMap;
use std::collections::HashSet;
use std::path::Path;

use rat_nodegraph::model::PortSpec;
use serde::Deserialize;
use serde::Serialize;

use crate::config;
use crate::credentials::NodeCredentialRefs;
use crate::credentials::SecretRef;
use crate::engine::workflow::NodeConfig;
use crate::engine::workflow::Workflow;
use crate::file_node::FileOperationKind;

const MAX_OPTIONAL_CWD_VALUES: usize = 1;
const MAX_OPTIONAL_BODY_VALUES: usize = 1;
const NICKEL_FILE_HEADER: &str = "# Generated by n8nclone. Edit through the typed Workflow contract below.";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableWorkflow {
    pub meta: PortableWorkflowMeta,
    pub nodes: Vec<PortableNode>,
    pub edges: Vec<PortableEdge>,
    pub configs: Vec<PortableNodeConfig>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableWorkflowMeta {
    pub name: String,
    pub description: String,
    pub created: String,
    pub modified: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableNode {
    pub id: u64,
    pub label: String,
    pub x: i32,
    pub y: i32,
    pub input_ports: Vec<PortablePort>,
    pub output_ports: Vec<PortablePort>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortablePort {
    pub id: u64,
    pub label: String,
    pub type_tag: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableEdge {
    pub source: u64,
    pub target: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableNodeConfig {
    pub node_id: u64,
    pub kind: String,
    pub command: String,
    pub cwd: Vec<String>,
    pub env: Vec<PortableEnvVar>,
    #[serde(default)]
    pub secret_env: Vec<PortableSecretEnvVar>,
    #[serde(default)]
    pub http_method: String,
    #[serde(default)]
    pub url: String,
    #[serde(default)]
    pub headers: Vec<PortableEnvVar>,
    #[serde(default)]
    pub body: Vec<String>,
    #[serde(default)]
    pub file_operation: String,
    #[serde(default)]
    pub file_path: String,
    #[serde(default)]
    pub file_content: Vec<String>,
    #[serde(default)]
    pub overwrite: bool,
    #[serde(default)]
    pub allowed_roots: Vec<String>,
    pub timeout_secs: u64,
    pub pipe_stdin: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableEnvVar {
    pub key: String,
    pub value: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortableSecretEnvVar {
    pub name: String,
    pub provider: String,
    pub key: String,
    #[serde(default)]
    pub field: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WorkflowFormatError {
    Nickel(String),
    Json(String),
    InvalidTimestamp(String),
    DuplicateNodeId(u64),
    DuplicatePortId(u64),
    DuplicateConfig(u64),
    MissingNodeConfig(u64),
    UnknownConfigNode(u64),
    UnknownEdgePort(u64),
    UnsupportedNodeKind(String),
    InvalidCwd { node_id: u64, count: usize },
    DuplicateEnvKey { node_id: u64, key: String },
    DuplicateSecretEnvName { node_id: u64, name: String },
    InvalidSecretField { node_id: u64, count: usize },
    InvalidHttpBody { node_id: u64, count: usize },
    InvalidFileContent { node_id: u64, count: usize },
    InvalidFileOperation { node_id: u64, operation: String },
    InvalidGraph(String),
}

impl std::fmt::Display for WorkflowFormatError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Nickel(message) => write!(f, "Nickel evaluation failed: {message}"),
            Self::Json(message) => write!(f, "workflow JSON decode failed: {message}"),
            Self::InvalidTimestamp(value) => write!(f, "invalid workflow timestamp: {value}"),
            Self::DuplicateNodeId(node_id) => write!(f, "duplicate node id: {node_id}"),
            Self::DuplicatePortId(port_id) => write!(f, "duplicate port id: {port_id}"),
            Self::DuplicateConfig(node_id) => write!(f, "duplicate node config for node: {node_id}"),
            Self::MissingNodeConfig(node_id) => write!(f, "missing node config for node: {node_id}"),
            Self::UnknownConfigNode(node_id) => write!(f, "node config references missing node: {node_id}"),
            Self::UnknownEdgePort(port_id) => write!(f, "edge references missing port: {port_id}"),
            Self::UnsupportedNodeKind(kind) => write!(f, "unsupported node kind: {kind}"),
            Self::InvalidCwd { node_id, count } => {
                write!(f, "node {node_id} has {count} cwd values; expected zero or one")
            }
            Self::DuplicateEnvKey { node_id, key } => write!(f, "node {node_id} has duplicate env key: {key}"),
            Self::DuplicateSecretEnvName { node_id, name } => {
                write!(f, "node {node_id} has duplicate secret env name: {name}")
            }
            Self::InvalidSecretField { node_id, count } => {
                write!(f, "node {node_id} has {count} secret field values; expected zero or one")
            }
            Self::InvalidHttpBody { node_id, count } => {
                write!(f, "node {node_id} has {count} HTTP body values; expected zero or one")
            }
            Self::InvalidFileContent { node_id, count } => {
                write!(f, "node {node_id} has {count} file content values; expected zero or one")
            }
            Self::InvalidFileOperation { node_id, operation } => {
                write!(f, "node {node_id} has invalid file operation: {operation}")
            }
            Self::InvalidGraph(message) => write!(f, "invalid graph: {message}"),
        }
    }
}

impl std::error::Error for WorkflowFormatError {}

// r[impl n8nclone.workflow_format.nickel.export]
pub fn workflow_to_portable(workflow: &Workflow) -> PortableWorkflow {
    let mut nodes = workflow
        .graph
        .nodes()
        .map(|node| PortableNode {
            id: node.id.0,
            label: node.label.clone(),
            x: node.x,
            y: node.y,
            input_ports: node.input_ports.iter().map(port_to_portable).collect(),
            output_ports: node.output_ports.iter().map(port_to_portable).collect(),
        })
        .collect::<Vec<_>>();
    nodes.sort_by_key(|node| node.id);

    let mut edges = workflow
        .graph
        .edges()
        .iter()
        .map(|edge| PortableEdge {
            source: edge.source.0,
            target: edge.target.0,
        })
        .collect::<Vec<_>>();
    edges.sort_by_key(|edge| (edge.source, edge.target));

    let mut configs = workflow
        .configs
        .iter()
        .map(|(node_id, config)| node_config_to_portable(*node_id, config, workflow.credentials.get(node_id)))
        .collect::<Vec<_>>();
    configs.sort_by_key(|config| config.node_id);

    PortableWorkflow {
        meta: PortableWorkflowMeta {
            name: workflow.meta.name.clone(),
            description: workflow.meta.description.clone(),
            created: workflow.meta.created.to_rfc3339(),
            modified: workflow.meta.modified.to_rfc3339(),
        },
        nodes,
        edges,
        configs,
    }
}

fn port_to_portable(port: &rat_nodegraph::model::Port) -> PortablePort {
    PortablePort {
        id: port.id.0,
        label: port.label.clone(),
        type_tag: port.type_tag.clone(),
    }
}

fn node_config_to_portable(
    node_id: u64,
    config: &NodeConfig,
    credentials: Option<&NodeCredentialRefs>,
) -> PortableNodeConfig {
    match config {
        NodeConfig::Shell {
            command,
            cwd,
            env,
            timeout_secs,
            pipe_stdin,
        } => {
            let mut env = env
                .iter()
                .map(|(key, value)| PortableEnvVar {
                    key: key.clone(),
                    value: value.clone(),
                })
                .collect::<Vec<_>>();
            env.sort_by(|left, right| left.key.cmp(&right.key));

            let mut secret_env = credentials
                .map(|credentials| {
                    credentials
                        .env
                        .iter()
                        .map(|(name, secret_ref)| PortableSecretEnvVar {
                            name: name.clone(),
                            provider: secret_ref.provider.clone(),
                            key: secret_ref.key.clone(),
                            field: secret_ref.field.iter().cloned().collect(),
                        })
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default();
            secret_env.sort_by(|left, right| left.name.cmp(&right.name));

            PortableNodeConfig {
                node_id,
                kind: "shell".to_string(),
                command: command.clone(),
                cwd: cwd.iter().cloned().collect(),
                env,
                secret_env,
                http_method: String::new(),
                url: String::new(),
                headers: Vec::new(),
                body: Vec::new(),
                file_operation: String::new(),
                file_path: String::new(),
                file_content: Vec::new(),
                overwrite: false,
                allowed_roots: Vec::new(),
                timeout_secs: *timeout_secs,
                pipe_stdin: *pipe_stdin,
            }
        }
        NodeConfig::Http {
            method,
            url,
            headers,
            body,
            timeout_secs,
        } => {
            let mut headers = headers
                .iter()
                .map(|(key, value)| PortableEnvVar {
                    key: key.clone(),
                    value: value.clone(),
                })
                .collect::<Vec<_>>();
            headers.sort_by(|left, right| left.key.cmp(&right.key));

            PortableNodeConfig {
                node_id,
                kind: "http".to_string(),
                command: String::new(),
                cwd: Vec::new(),
                env: Vec::new(),
                secret_env: Vec::new(),
                http_method: method.clone(),
                url: url.clone(),
                headers,
                body: body.iter().cloned().collect(),
                file_operation: String::new(),
                file_path: String::new(),
                file_content: Vec::new(),
                overwrite: false,
                allowed_roots: Vec::new(),
                timeout_secs: *timeout_secs,
                pipe_stdin: false,
            }
        }
        NodeConfig::File {
            operation,
            path,
            content,
            overwrite,
            allowed_roots,
        } => PortableNodeConfig {
            node_id,
            kind: "file".to_string(),
            command: String::new(),
            cwd: Vec::new(),
            env: Vec::new(),
            secret_env: Vec::new(),
            http_method: String::new(),
            url: String::new(),
            headers: Vec::new(),
            body: Vec::new(),
            file_operation: file_operation_label(*operation).to_string(),
            file_path: path.clone(),
            file_content: content.iter().cloned().collect(),
            overwrite: *overwrite,
            allowed_roots: allowed_roots.clone(),
            timeout_secs: 0,
            pipe_stdin: false,
        },
    }
}

// r[impl n8nclone.workflow_format.nickel.import]
pub fn portable_to_workflow(portable: PortableWorkflow) -> Result<Workflow, WorkflowFormatError> {
    validate_portable_identity(&portable)?;

    let created = parse_timestamp(&portable.meta.created)?;
    let modified = parse_timestamp(&portable.meta.modified)?;
    let mut workflow = Workflow::new(portable.meta.name.clone());
    workflow.meta.description = portable.meta.description.clone();
    workflow.meta.created = created;
    workflow.meta.modified = modified;

    let mut node_id_map = HashMap::new();
    let mut port_id_map = HashMap::new();

    for portable_node in &portable.nodes {
        let input_specs = portable_node
            .input_ports
            .iter()
            .map(|port| PortSpec::new(port.label.clone(), port.type_tag.clone()))
            .collect::<Vec<_>>();
        let output_specs = portable_node
            .output_ports
            .iter()
            .map(|port| PortSpec::new(port.label.clone(), port.type_tag.clone()))
            .collect::<Vec<_>>();
        let new_node_id = workflow.graph.add_node(portable_node.label.clone(), &input_specs, &output_specs);
        if let Some(node) = workflow.graph.node_mut(new_node_id) {
            node.x = portable_node.x;
            node.y = portable_node.y;
            for (old_port, new_port) in portable_node.input_ports.iter().zip(&node.input_ports) {
                port_id_map.insert(old_port.id, new_port.id);
            }
            for (old_port, new_port) in portable_node.output_ports.iter().zip(&node.output_ports) {
                port_id_map.insert(old_port.id, new_port.id);
            }
        }
        node_id_map.insert(portable_node.id, new_node_id);
    }

    for config in &portable.configs {
        let new_node_id =
            *node_id_map.get(&config.node_id).ok_or(WorkflowFormatError::UnknownConfigNode(config.node_id))?;
        workflow.set_node_config(new_node_id, portable_config_to_node_config(config)?);
        workflow.set_node_credentials(new_node_id, portable_config_to_node_credentials(config)?);
    }

    for portable_node in &portable.nodes {
        if !portable.configs.iter().any(|config| config.node_id == portable_node.id) {
            return Err(WorkflowFormatError::MissingNodeConfig(portable_node.id));
        }
    }

    for edge in &portable.edges {
        let source = *port_id_map.get(&edge.source).ok_or(WorkflowFormatError::UnknownEdgePort(edge.source))?;
        let target = *port_id_map.get(&edge.target).ok_or(WorkflowFormatError::UnknownEdgePort(edge.target))?;
        workflow
            .graph
            .add_edge(source, target)
            .map_err(|error| WorkflowFormatError::InvalidGraph(error.to_string()))?;
    }

    Ok(workflow)
}

fn validate_portable_identity(portable: &PortableWorkflow) -> Result<(), WorkflowFormatError> {
    let mut node_ids = HashSet::new();
    let mut port_ids = HashSet::new();
    let mut config_node_ids = HashSet::new();

    for node in &portable.nodes {
        if !node_ids.insert(node.id) {
            return Err(WorkflowFormatError::DuplicateNodeId(node.id));
        }
        for port in node.input_ports.iter().chain(&node.output_ports) {
            if !port_ids.insert(port.id) {
                return Err(WorkflowFormatError::DuplicatePortId(port.id));
            }
        }
    }

    for config in &portable.configs {
        if !config_node_ids.insert(config.node_id) {
            return Err(WorkflowFormatError::DuplicateConfig(config.node_id));
        }
    }

    Ok(())
}

fn portable_config_to_node_config(config: &PortableNodeConfig) -> Result<NodeConfig, WorkflowFormatError> {
    match config.kind.as_str() {
        "shell" => portable_shell_config_to_node_config(config),
        "http" => portable_http_config_to_node_config(config),
        "file" => portable_file_config_to_node_config(config),
        _ => Err(WorkflowFormatError::UnsupportedNodeKind(config.kind.clone())),
    }
}

fn portable_shell_config_to_node_config(config: &PortableNodeConfig) -> Result<NodeConfig, WorkflowFormatError> {
    if config.cwd.len() > MAX_OPTIONAL_CWD_VALUES {
        return Err(WorkflowFormatError::InvalidCwd {
            node_id: config.node_id,
            count: config.cwd.len(),
        });
    }

    let mut env = HashMap::new();
    for env_var in &config.env {
        if env.insert(env_var.key.clone(), env_var.value.clone()).is_some() {
            return Err(WorkflowFormatError::DuplicateEnvKey {
                node_id: config.node_id,
                key: env_var.key.clone(),
            });
        }
    }

    Ok(NodeConfig::Shell {
        command: config.command.clone(),
        cwd: config.cwd.first().cloned(),
        env,
        timeout_secs: config.timeout_secs,
        pipe_stdin: config.pipe_stdin,
    })
}

fn portable_http_config_to_node_config(config: &PortableNodeConfig) -> Result<NodeConfig, WorkflowFormatError> {
    if config.body.len() > MAX_OPTIONAL_BODY_VALUES {
        return Err(WorkflowFormatError::InvalidHttpBody {
            node_id: config.node_id,
            count: config.body.len(),
        });
    }

    let mut headers = HashMap::new();
    for header in &config.headers {
        if headers.insert(header.key.clone(), header.value.clone()).is_some() {
            return Err(WorkflowFormatError::DuplicateEnvKey {
                node_id: config.node_id,
                key: header.key.clone(),
            });
        }
    }

    Ok(NodeConfig::Http {
        method: config.http_method.clone(),
        url: config.url.clone(),
        headers,
        body: config.body.first().cloned(),
        timeout_secs: config.timeout_secs,
    })
}

fn portable_file_config_to_node_config(config: &PortableNodeConfig) -> Result<NodeConfig, WorkflowFormatError> {
    if config.file_content.len() > MAX_OPTIONAL_BODY_VALUES {
        return Err(WorkflowFormatError::InvalidFileContent {
            node_id: config.node_id,
            count: config.file_content.len(),
        });
    }
    Ok(NodeConfig::File {
        operation: parse_file_operation(config.node_id, &config.file_operation)?,
        path: config.file_path.clone(),
        content: config.file_content.first().cloned(),
        overwrite: config.overwrite,
        allowed_roots: config.allowed_roots.clone(),
    })
}

fn parse_file_operation(node_id: u64, operation: &str) -> Result<FileOperationKind, WorkflowFormatError> {
    match operation {
        "read" => Ok(FileOperationKind::Read),
        "write" => Ok(FileOperationKind::Write),
        "append" => Ok(FileOperationKind::Append),
        _ => Err(WorkflowFormatError::InvalidFileOperation {
            node_id,
            operation: operation.to_string(),
        }),
    }
}

fn file_operation_label(operation: FileOperationKind) -> &'static str {
    match operation {
        FileOperationKind::Read => "read",
        FileOperationKind::Write => "write",
        FileOperationKind::Append => "append",
    }
}

fn portable_config_to_node_credentials(config: &PortableNodeConfig) -> Result<NodeCredentialRefs, WorkflowFormatError> {
    let mut env = HashMap::new();
    for secret_env in &config.secret_env {
        if secret_env.field.len() > MAX_OPTIONAL_CWD_VALUES {
            return Err(WorkflowFormatError::InvalidSecretField {
                node_id: config.node_id,
                count: secret_env.field.len(),
            });
        }
        if env
            .insert(
                secret_env.name.clone(),
                SecretRef::new(secret_env.provider.clone(), secret_env.key.clone(), secret_env.field.first().cloned()),
            )
            .is_some()
        {
            return Err(WorkflowFormatError::DuplicateSecretEnvName {
                node_id: config.node_id,
                name: secret_env.name.clone(),
            });
        }
    }
    Ok(NodeCredentialRefs { env })
}

fn parse_timestamp(value: &str) -> Result<chrono::DateTime<chrono::Utc>, WorkflowFormatError> {
    chrono::DateTime::parse_from_rfc3339(value)
        .map(|timestamp| timestamp.with_timezone(&chrono::Utc))
        .map_err(|_| WorkflowFormatError::InvalidTimestamp(value.to_string()))
}

// r[impl n8nclone.workflow_format.nickel.export]
pub fn workflow_to_nickel(workflow: &Workflow) -> String {
    portable_to_nickel(&workflow_to_portable(workflow))
}

pub fn portable_to_nickel(portable: &PortableWorkflow) -> String {
    let mut output = String::new();
    output.push_str(NICKEL_FILE_HEADER);
    output.push_str("\n\n");
    output.push_str(nickel_contract_prelude());
    output.push_str("(\n");
    render_portable_workflow(&mut output, portable);
    output.push_str(") | Workflow\n");
    output
}

fn nickel_contract_prelude() -> &'static str {
    "let Port = { id | Number, label | String, type_tag | String } in\nlet Node = { id | Number, label | String, x | Number, y | Number, input_ports | Array Port, output_ports | Array Port } in\nlet Edge = { source | Number, target | Number } in\nlet EnvVar = { key | String, value | String } in\nlet SecretEnvVar = { name | String, provider | String, key | String, field | Array String } in\nlet NodeConfig = { node_id | Number, kind | String, command | String, cwd | Array String, env | Array EnvVar, secret_env | Array SecretEnvVar, http_method | String, url | String, headers | Array EnvVar, body | Array String, file_operation | String, file_path | String, file_content | Array String, overwrite | Bool, allowed_roots | Array String, timeout_secs | Number, pipe_stdin | Bool } in\nlet Meta = { name | String, description | String, created | String, modified | String } in\nlet Workflow = { meta | Meta, nodes | Array Node, edges | Array Edge, configs | Array NodeConfig } in\n"
}

fn render_portable_workflow(output: &mut String, portable: &PortableWorkflow) {
    output.push_str("{\n");
    output.push_str("  meta = {\n");
    output.push_str(&format!("    name = {},\n", quoted(&portable.meta.name)));
    output.push_str(&format!("    description = {},\n", quoted(&portable.meta.description)));
    output.push_str(&format!("    created = {},\n", quoted(&portable.meta.created)));
    output.push_str(&format!("    modified = {},\n", quoted(&portable.meta.modified)));
    output.push_str("  },\n");
    output.push_str("  nodes = [\n");
    for node in &portable.nodes {
        render_node(output, node);
    }
    output.push_str("  ],\n");
    output.push_str("  edges = [\n");
    for edge in &portable.edges {
        output.push_str(&format!("    {{ source = {}, target = {} }},\n", edge.source, edge.target));
    }
    output.push_str("  ],\n");
    output.push_str("  configs = [\n");
    for config in &portable.configs {
        render_config(output, config);
    }
    output.push_str("  ],\n");
    output.push_str("}\n");
}

fn render_node(output: &mut String, node: &PortableNode) {
    output.push_str("    {\n");
    output.push_str(&format!("      id = {},\n", node.id));
    output.push_str(&format!("      label = {},\n", quoted(&node.label)));
    output.push_str(&format!("      x = {},\n", node.x));
    output.push_str(&format!("      y = {},\n", node.y));
    output.push_str("      input_ports = [\n");
    for port in &node.input_ports {
        render_port(output, port);
    }
    output.push_str("      ],\n");
    output.push_str("      output_ports = [\n");
    for port in &node.output_ports {
        render_port(output, port);
    }
    output.push_str("      ],\n");
    output.push_str("    },\n");
}

fn render_port(output: &mut String, port: &PortablePort) {
    output.push_str(&format!(
        "        {{ id = {}, label = {}, type_tag = {} }},\n",
        port.id,
        quoted(&port.label),
        quoted(&port.type_tag),
    ));
}

fn render_config(output: &mut String, config: &PortableNodeConfig) {
    output.push_str("    {\n");
    output.push_str(&format!("      node_id = {},\n", config.node_id));
    output.push_str(&format!("      kind = {},\n", quoted(&config.kind)));
    output.push_str(&format!("      command = {},\n", quoted(&config.command)));
    output.push_str("      cwd = [");
    for cwd in &config.cwd {
        output.push_str(&format!("{}, ", quoted(cwd)));
    }
    output.push_str("],\n");
    output.push_str("      env = [\n");
    for env in &config.env {
        output.push_str(&format!("        {{ key = {}, value = {} }},\n", quoted(&env.key), quoted(&env.value),));
    }
    output.push_str("      ],\n");
    output.push_str("      secret_env = [\n");
    for secret_env in &config.secret_env {
        output.push_str(&format!(
            "        {{ name = {}, provider = {}, key = {}, field = [",
            quoted(&secret_env.name),
            quoted(&secret_env.provider),
            quoted(&secret_env.key),
        ));
        for field in &secret_env.field {
            output.push_str(&format!("{}, ", quoted(field)));
        }
        output.push_str("] },\n");
    }
    output.push_str("      ],\n");
    output.push_str(&format!("      http_method = {},\n", quoted(&config.http_method)));
    output.push_str(&format!("      url = {},\n", quoted(&config.url)));
    output.push_str("      headers = [\n");
    for header in &config.headers {
        output.push_str(&format!("        {{ key = {}, value = {} }},\n", quoted(&header.key), quoted(&header.value),));
    }
    output.push_str("      ],\n");
    output.push_str("      body = [");
    for body in &config.body {
        output.push_str(&format!("{}, ", quoted(body)));
    }
    output.push_str("],\n");
    output.push_str(&format!("      file_operation = {},\n", quoted(&config.file_operation)));
    output.push_str(&format!("      file_path = {},\n", quoted(&config.file_path)));
    output.push_str("      file_content = [");
    for content in &config.file_content {
        output.push_str(&format!("{}, ", quoted(content)));
    }
    output.push_str("],\n");
    output.push_str(&format!("      overwrite = {},\n", config.overwrite));
    output.push_str("      allowed_roots = [");
    for root in &config.allowed_roots {
        output.push_str(&format!("{}, ", quoted(root)));
    }
    output.push_str("],\n");
    output.push_str(&format!("      timeout_secs = {},\n", config.timeout_secs));
    output.push_str(&format!("      pipe_stdin = {},\n", config.pipe_stdin));
    output.push_str("    },\n");
}

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("JSON string serialization cannot fail")
}

