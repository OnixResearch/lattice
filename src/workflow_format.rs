// r[impl n8nclone.workflow_format.triggers.nickel]
fn trigger_to_portable(trigger: &TriggerDefinition) -> PortableTrigger {
    let parts = portable_trigger_kind_parts(trigger);
    let (auth_kind, auth_provider, auth_key, auth_field, auth_header) = portable_auth_parts(parts.webhook.as_ref());
    PortableTrigger {
        id: trigger.id.clone(),
        workflow_name: trigger.workflow_name.clone(),
        enabled: trigger.enabled,
        kind: parts.kind.to_string(),
        webhook_method: parts.webhook.as_ref().map(|webhook| webhook.method.clone()).unwrap_or_default(),
        webhook_path: parts.webhook.as_ref().map(|webhook| webhook.path.clone()).unwrap_or_default(),
        webhook_content_types: parts
            .webhook
            .as_ref()
            .map(|webhook| webhook.accepted_content_types.clone())
            .unwrap_or_default(),
        auth_kind,
        auth_provider,
        auth_key,
        auth_field,
        auth_header,
        schedule_interval_secs: parts.schedule.map(|schedule| schedule.0.interval_secs()).unwrap_or_default(),
        schedule_next_run_epoch_ms: parts.schedule.map(|schedule| schedule.2).unwrap_or_default(),
        schedule_missed_run_policy: parts
            .schedule
            .map(|schedule| missed_run_policy_label(schedule.1).to_string())
            .unwrap_or_default(),
        input_bindings: trigger.input_bindings.iter().map(trigger_binding_to_portable).collect(),
        overlap_policy: overlap_policy_label(trigger.overlap_policy).to_string(),
        idempotency_policy: idempotency_policy_label(&trigger.idempotency_policy).to_string(),
        idempotency_json_pointer: match &trigger.idempotency_policy {
            IdempotencyPolicy::PayloadJsonPointer(pointer) => pointer.clone(),
            IdempotencyPolicy::None | IdempotencyPolicy::EventKey => String::new(),
        },
    }
}

fn portable_trigger_kind_parts(trigger: &TriggerDefinition) -> PortableTriggerKindParts {
    match &trigger.kind {
        TriggerKind::Manual => PortableTriggerKindParts {
            kind: TRIGGER_KIND_MANUAL,
            webhook: None,
            schedule: None,
        },
        TriggerKind::Schedule {
            recurrence,
            missed_run_policy,
            next_run_epoch_ms,
        } => PortableTriggerKindParts {
            kind: TRIGGER_KIND_SCHEDULE,
            webhook: None,
            schedule: Some((*recurrence, *missed_run_policy, *next_run_epoch_ms)),
        },
        TriggerKind::Webhook(webhook) => PortableTriggerKindParts {
            kind: TRIGGER_KIND_WEBHOOK,
            webhook: Some(webhook.clone()),
            schedule: None,
        },
    }
}

fn portable_auth_parts(webhook: Option<&WebhookTrigger>) -> (String, String, String, Vec<String>, String) {
    let Some(webhook) = webhook else {
        return (String::new(), String::new(), String::new(), Vec::new(), String::new());
    };
    match &webhook.auth_policy {
        WebhookAuthPolicy::NoAuthLocalOnly => {
            (AUTH_KIND_NONE.to_string(), String::new(), String::new(), Vec::new(), String::new())
        }
        WebhookAuthPolicy::Bearer { secret_ref } => (
            AUTH_KIND_BEARER.to_string(),
            secret_ref.provider.clone(),
            secret_ref.key.clone(),
            secret_ref.field.iter().cloned().collect(),
            String::new(),
        ),
        WebhookAuthPolicy::Blake3Signature { secret_ref, header } => (
            AUTH_KIND_BLAKE3.to_string(),
            secret_ref.provider.clone(),
            secret_ref.key.clone(),
            secret_ref.field.iter().cloned().collect(),
            header.clone(),
        ),
    }
}

fn trigger_binding_to_portable(binding: &TriggerInputBinding) -> PortableTriggerInputBinding {
    let (source_kind, source_name) = match &binding.source {
        TriggerPayloadSource::JsonPointer(pointer) => (SOURCE_KIND_JSON, pointer.clone()),
        TriggerPayloadSource::QueryParam(name) => (SOURCE_KIND_QUERY, name.clone()),
        TriggerPayloadSource::Header(name) => (SOURCE_KIND_HEADER, name.clone()),
        TriggerPayloadSource::RawBody => (SOURCE_KIND_RAW, String::new()),
    };
    PortableTriggerInputBinding {
        input_label: binding.input_label.clone(),
        source_kind: source_kind.to_string(),
        source_name,
        type_tag: binding.type_tag.clone(),
        required: binding.required,
    }
}

fn portable_trigger_to_trigger(config: &PortableTrigger) -> Result<TriggerDefinition, WorkflowFormatError> {
    Ok(TriggerDefinition {
        id: config.id.clone(),
        workflow_name: config.workflow_name.clone(),
        enabled: config.enabled,
        kind: portable_trigger_kind(config)?,
        input_bindings: config
            .input_bindings
            .iter()
            .map(portable_trigger_binding_to_binding)
            .collect::<Result<Vec<_>, _>>()?,
        overlap_policy: parse_overlap_policy(&config.overlap_policy)?,
        idempotency_policy: parse_idempotency_policy(config),
    })
}

fn portable_trigger_kind(config: &PortableTrigger) -> Result<TriggerKind, WorkflowFormatError> {
    match config.kind.as_str() {
        TRIGGER_KIND_MANUAL => Ok(TriggerKind::Manual),
        TRIGGER_KIND_SCHEDULE => Ok(TriggerKind::Schedule {
            recurrence: RecurrenceRule::EverySeconds {
                interval_secs: config.schedule_interval_secs,
            },
            missed_run_policy: parse_missed_run_policy(&config.schedule_missed_run_policy)?,
            next_run_epoch_ms: config.schedule_next_run_epoch_ms,
        }),
        TRIGGER_KIND_WEBHOOK => Ok(TriggerKind::Webhook(WebhookTrigger {
            method: config.webhook_method.clone(),
            path: config.webhook_path.clone(),
            accepted_content_types: config.webhook_content_types.clone(),
            auth_policy: portable_auth_policy(config)?,
        })),
        _ => Err(invalid_trigger(config, "unknown trigger kind")),
    }
}

fn portable_auth_policy(config: &PortableTrigger) -> Result<WebhookAuthPolicy, WorkflowFormatError> {
    match config.auth_kind.as_str() {
        AUTH_KIND_NONE | "" => Ok(WebhookAuthPolicy::NoAuthLocalOnly),
        AUTH_KIND_BEARER => Ok(WebhookAuthPolicy::Bearer {
            secret_ref: portable_trigger_secret_ref(config),
        }),
        AUTH_KIND_BLAKE3 => Ok(WebhookAuthPolicy::Blake3Signature {
            secret_ref: portable_trigger_secret_ref(config),
            header: config.auth_header.clone(),
        }),
        _ => Err(invalid_trigger(config, "unknown webhook auth kind")),
    }
}

fn portable_trigger_secret_ref(config: &PortableTrigger) -> SecretRef {
    SecretRef::new(config.auth_provider.clone(), config.auth_key.clone(), config.auth_field.first().cloned())
}

fn portable_trigger_binding_to_binding(
    binding: &PortableTriggerInputBinding,
) -> Result<TriggerInputBinding, WorkflowFormatError> {
    let source = match binding.source_kind.as_str() {
        SOURCE_KIND_JSON => TriggerPayloadSource::JsonPointer(binding.source_name.clone()),
        SOURCE_KIND_QUERY => TriggerPayloadSource::QueryParam(binding.source_name.clone()),
        SOURCE_KIND_HEADER => TriggerPayloadSource::Header(binding.source_name.clone()),
        SOURCE_KIND_RAW => TriggerPayloadSource::RawBody,
        _ => {
            return Err(WorkflowFormatError::InvalidTriggerConfig {
                trigger_id: binding.input_label.clone(),
                message: "unknown trigger binding source".to_string(),
            });
        }
    };
    Ok(TriggerInputBinding {
        input_label: binding.input_label.clone(),
        source,
        type_tag: binding.type_tag.clone(),
        required: binding.required,
    })
}

